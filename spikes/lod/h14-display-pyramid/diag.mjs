import path from 'node:path';
import { chromium } from 'playwright';
const b = await chromium.launch({headless:true});
const c = await b.newContext({viewport:{width:1600,height:1000},deviceScaleFactor:1});
const p = await c.newPage();
p.on('pageerror',e=>console.log('ERR',String(e)));
await p.goto('file:///C:/Dev/windrose/spikes/lod/h14-display-pyramid/index.html?probe=1&genBudgetMs=4&fade=150');
await p.waitForFunction(()=>!!window.__lod&&!!window.__lod.ready);
await p.evaluate(()=>window.__lod.ready);
const r = await p.evaluate(async ()=>{
  const wait = async (n)=>{for(let i=0;i<n;i++) await new Promise(r=>requestAnimationFrame(r));};
  window.__lod.reset(); window.__lod.setZoom(8); await wait(40);
  const cv = document.getElementById('stage');
  const ct = cv.getContext('2d',{willReadFrequently:true});
  const px = ()=>[...ct.getImageData(800,500,1,1).data].slice(0,3);
  const w = window.__lod.worldAt(800,500);
  const before = px();
  const hit = window.__lod.pick(w.x,w.y);
  const ed = window.__lod.paint(w.x,w.y,'#ff0000');
  await wait(40);
  const after = px();
  const m = window.__lod.metrics();
  return {w, hit, ed, before, after, level:m.level, pending:m.pendingTiles, needed:m.neededTiles, cached:m.tilesCached};
});
console.log(JSON.stringify(r,null,1));
