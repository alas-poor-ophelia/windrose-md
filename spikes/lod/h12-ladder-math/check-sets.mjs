import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const tmp = path.join(HERE, 'dist', 'lattice.cjs');
await build({ entryPoints: [path.join(HERE,'lattice.ts')], bundle:true, format:'cjs', platform:'node', outfile:tmp, logLevel:'warning' });
const m = await import(pathToFileURL(tmp).href + '?t=' + Date.now());
const ring7 = m.buildLadder(m.LADDERS.ring7s15);
const m13 = m.buildLadder(m.LADDERS.m13);
const r7e = m.buildLadder(m.LADDERS.r7exact);
const key = (c)=>c.q+','+c.r;
const A = new Set(ring7.childSet.map(key));
const B = new Set(m13.childSet.map(key));
const C = new Set(r7e.childSet.map(key));
const onlyA = [...A].filter(k=>!B.has(k));
const onlyB = [...B].filter(k=>!A.has(k));
// are the m13 differences ties?
const tieSet = new Set(m13.childSet.filter(c=>m13.parentOf(c.q,c.r).tie).map(key));
console.log('--- m13 vs ring7 ---');
console.log('onlyInRing7 (12):', onlyA.join(' '));
console.log('onlyInM13  (12):', onlyB.join(' '));
console.log('m13 tie cells   :', [...tieSet].join(' '));
console.log('onlyInM13 all ties?', onlyB.every(k=>tieSet.has(k)));
console.log('--- r7exact (15,-7) ---');
console.log('K', r7e.K, 'scale', r7e.m.toFixed(6), 'rotDeg', r7e.thetaDeg.toFixed(6), 'count', C.size);
console.log('set == ring7 rosette?', C.size===A.size && [...C].every(k=>A.has(k)));
console.log('onlyInR7exact:', [...C].filter(k=>!A.has(k)).join(' '));
console.log('onlyInRosette:', [...A].filter(k=>!C.has(k)).join(' '));
console.log('ties', r7e.childSet.filter(c=>r7e.parentOf(c.q,c.r).tie).length);
const cont = m.measureContainment(r7e, 1001);
const bnd = m.measureBoundary(r7e, 240);
console.log('containment uncovered%', cont.parentUncoveredPct.toFixed(3), 'outside%', cont.childOutsidePct.toFixed(3), 'areaRatio', cont.areaRatio.toFixed(5));
console.log('boundary meanPx', bnd.meanPx, 'maxPx', bnd.maxPx, 'meanPct', bnd.meanPctOfParentSize, 'maxPct', bnd.maxPctOfParentSize, 'perEdge', bnd.perEdgeMeanPx.join(','));
