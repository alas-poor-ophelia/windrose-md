/**
 * partyNoteOperations.ts
 *
 * Generates and maintains a party pin's vault note: a markdown table of the
 * pin's in-range results, updated by the same recalculation pipeline that
 * feeds the canvas overlay.
 *
 * Safety rules:
 * - Every generated note carries a frontmatter marker with the owning pin's
 *   id. Updates and deletions verify the marker first — a user note that
 *   happens to share the path is never overwritten or trashed.
 * - Generated content lives between two HTML comment markers. Updates
 *   replace only that region (atomically via vault.process); user text and
 *   frontmatter outside it are kept.
 * - Writes are change-detected: identical content is never rewritten, so
 *   file modification times (and sync) stay quiet while nothing changes.
 * - A renamed note is found again by its marker, and the rename listener in
 *   main.ts broadcasts renames so mounted beacons update their stored path.
 * - A manually deleted note is recreated on the next update.
 */

import type { App } from 'obsidian';
import type { PartyPin } from '#types/core/map.types';
import type { PartyRangeResults } from '#types/objects/partyRange.types';
import type { RelatedNotes } from '../objects/partyRelatedNotes';

import { normalizePath, TFile as ObsidianTFile } from 'obsidian';
import { generateDeepLink } from './deepLinkHandler';

/** Frontmatter key marking a note as generated by a party pin */
const PARTY_NOTE_MARKER_KEY = 'windrose-party-pin';

/** Region markers around the plugin-owned part of the note */
const PARTY_NOTE_REGION_START = '<!-- windrose-beacon:start -->';
const PARTY_NOTE_REGION_END = '<!-- windrose-beacon:end -->';

/** Deeplink zoom used in note rows — fixed so content never churns with the viewport */
const NOTE_DEEP_LINK_ZOOM = 1.175;

/** Context about the map hosting the pin, for headings and deeplinks */
export interface PartyNoteContext {
  mapId: string;
  mapName: string;
  /** Path of the note hosting the map; '' when the map lives in a full-pane view */
  mapNotePath: string;
  /** Display unit for the pin's range (e.g. 'ft', 'mi'); omitted → bare number */
  distanceUnit?: string;
}

/** Outcome of an upsert, for caller feedback */
export type PartyNoteWriteResult = 'created' | 'updated' | 'unchanged' | 'blocked';

/** Outcome of a delete request */
export type PartyNoteDeleteResult = 'deleted' | 'not-found' | 'not-owned';

/**
 * Make a label safe to use as a note file name.
 * Falls back to 'Party' when nothing survives.
 */
function sanitizePartyNoteFileName(label: string): string {
  const cleaned = label
    .replace(/[\\/:*?"<>|#^[\]]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return cleaned === '' ? 'Party' : cleaned;
}

/**
 * Build the full vault path for a pin's note in the given folder.
 * @param folder - Vault folder ('' for the vault root)
 */
function buildPartyNotePath(folder: string, label: string): string {
  const fileName = `${sanitizePartyNoteFileName(label)} - Nearby.md`;
  const trimmed = folder.trim().replace(/^\/+|\/+$/g, '');
  return normalizePath(trimmed === '' ? fileName : `${trimmed}/${fileName}`);
}

/** Escape a string for use inside a markdown table cell */
function escapeTableCell(value: string): string {
  return value.replace(/\|/g, '\\|');
}

/** Render a wiki link with the note's basename as display text */
function wikiLinkCell(notePath: string): string {
  const target = notePath.replace(/\.md$/, '');
  const display = target.split('/').pop() ?? target;
  return `[[${escapeTableCell(target)}\\|${escapeTableCell(display)}]]`;
}

/** Render a related-notes cell: capped links plus an explicit overflow */
function relatedCell(related: RelatedNotes | undefined): string {
  if (related == null || related.paths.length === 0) return '—';
  const links = related.paths.map(wikiLinkCell).join(', ');
  return related.overflow > 0 ? `${links} +${related.overflow} more` : links;
}

/** Per-result travel-time labels for the note's Travel column (PP-35) */
export interface PartyNoteTravelLabels {
  /** Keyed by linked result note path */
  linked: Map<string, string>;
  /** Keyed by unlinked result object id */
  unlinked: Map<string, string>;
  /** Keyed by in-range beacon pin id */
  beacons?: Map<string, string>;
}

/**
 * Render the note's full markdown content for the current results.
 * Pure — content equality doubles as the change detector.
 * @param related - Per-result related notes (keyed by note path); when
 *                  provided, the table gains a Related column
 * @param travel - Per-result travel-time labels; when provided, both
 *                 tables gain a Travel column (PP-35)
 */
function buildPartyNoteContent(
  pin: PartyPin,
  results: PartyRangeResults,
  context: PartyNoteContext,
  related?: Map<string, RelatedNotes>,
  travel?: PartyNoteTravelLabels
): string {
  const lines: string[] = [];
  lines.push('---');
  lines.push(`${PARTY_NOTE_MARKER_KEY}: ${pin.id}`);
  lines.push('---');
  lines.push('');
  lines.push(PARTY_NOTE_REGION_START);
  // No H1 — the note title already carries "<label> - Nearby"
  const rangeLabel = context.distanceUnit != null && context.distanceUnit !== ''
    ? `${pin.range} ${context.distanceUnit}`
    : `${pin.range}`;
  const mapClause = context.mapName !== '' ? ` on **${context.mapName}**` : '';
  lines.push(`Within **${rangeLabel}** of the beacon${mapClause}.`);
  lines.push('');

  if (results.linked.length === 0 && results.unlinked.length === 0 && results.beacons.length === 0) {
    lines.push('*Nothing in range.*');
    lines.push(PARTY_NOTE_REGION_END);
    lines.push('');
    return lines.join('\n');
  }

  if (results.linked.length > 0) {
    const hasDeepLinks = context.mapNotePath !== '';
    const hasRelated = related != null;
    const hasTravel = travel != null;
    const header = ['Note', 'Distance', ...(hasTravel ? ['Travel'] : []), ...(hasRelated ? ['Related'] : []), ...(hasDeepLinks ? ['Map'] : [])];
    lines.push(`| ${header.join(' | ')} |`);
    lines.push(`|${header.map(() => ' --- ').join('|')}|`);
    for (const result of results.linked) {
      const linkTarget = result.notePath.replace(/\.md$/, '');
      const link = `[[${escapeTableCell(linkTarget)}\\|${escapeTableCell(result.displayName)}]]`;
      const cells = [link, escapeTableCell(result.distanceLabel)];
      if (hasTravel) {
        cells.push(escapeTableCell(travel.linked.get(result.notePath) ?? '—'));
      }
      if (hasRelated) {
        cells.push(relatedCell(related.get(result.notePath)));
      }
      if (hasDeepLinks) {
        const url = generateDeepLink(
          context.mapNotePath, context.mapId,
          result.position.x, result.position.y,
          NOTE_DEEP_LINK_ZOOM, ''
        );
        cells.push(`[show](${url})`);
      }
      lines.push(`| ${cells.join(' | ')} |`);
    }
    lines.push('');
  }

  if (results.unlinked.length > 0) {
    lines.push('## Unlinked');
    lines.push('');
    if (travel != null) {
      lines.push('| Marker | Distance | Travel |');
      lines.push('| --- | --- | --- |');
      for (const result of results.unlinked) {
        const label = travel.unlinked.get(result.objectId) ?? '—';
        lines.push(`| ${escapeTableCell(result.label)} | ${escapeTableCell(result.distanceLabel)} | ${escapeTableCell(label)} |`);
      }
    } else {
      lines.push('| Marker | Distance |');
      lines.push('| --- | --- |');
      for (const result of results.unlinked) {
        lines.push(`| ${escapeTableCell(result.label)} | ${escapeTableCell(result.distanceLabel)} |`);
      }
    }
    lines.push('');
  }

  if (results.beacons.length > 0) {
    lines.push('## Beacons');
    lines.push('');
    const hasDeepLinks = context.mapNotePath !== '';
    const hasTravel = travel != null;
    const header = ['Beacon', 'Distance', ...(hasTravel ? ['Travel'] : []), ...(hasDeepLinks ? ['Map'] : [])];
    lines.push(`| ${header.join(' | ')} |`);
    lines.push(`|${header.map(() => ' --- ').join('|')}|`);
    for (const result of results.beacons) {
      // A beacon with a generated note links to it; the rest are plain labels
      const name = result.notePath != null
        ? `[[${escapeTableCell(result.notePath.replace(/\.md$/, ''))}\\|${escapeTableCell(result.label)}]]`
        : escapeTableCell(result.label);
      const cells = [name, escapeTableCell(result.distanceLabel)];
      if (hasTravel) {
        cells.push(escapeTableCell(travel.beacons?.get(result.pinId) ?? '—'));
      }
      if (hasDeepLinks) {
        const url = generateDeepLink(
          context.mapNotePath, context.mapId,
          result.position.x, result.position.y,
          NOTE_DEEP_LINK_ZOOM, ''
        );
        cells.push(`[show](${url})`);
      }
      lines.push(`| ${cells.join(' | ')} |`);
    }
    lines.push('');
  }

  lines.push(PARTY_NOTE_REGION_END);
  lines.push('');
  return lines.join('\n');
}

/**
 * Merge freshly generated note content into the note's current content.
 * Only the marker region is replaced; frontmatter and user text outside it
 * are kept. A legacy note (generated before the markers existed) has NEITHER
 * marker and was wholly generated, so it is replaced in full. A damaged region
 * (only one marker, or end before start) means the user edited around it: the
 * note is left as it is rather than replacing their prose (wave-5 finding 8).
 */
function mergePartyNoteContent(current: string, generated: string): string {
  const genStart = generated.indexOf(PARTY_NOTE_REGION_START);
  const genEnd = generated.indexOf(PARTY_NOTE_REGION_END);
  if (!current.includes(PARTY_NOTE_REGION_START) && !current.includes(PARTY_NOTE_REGION_END)) return generated;
  const curStart = current.indexOf(PARTY_NOTE_REGION_START);
  const curEnd = curStart === -1 ? -1 : current.indexOf(PARTY_NOTE_REGION_END, curStart);
  if (genStart === -1 || genEnd === -1 || curStart === -1 || curEnd === -1) return current;
  const region = generated.slice(genStart, genEnd + PARTY_NOTE_REGION_END.length);
  return current.slice(0, curStart) + region + current.slice(curEnd + PARTY_NOTE_REGION_END.length);
}

/**
 * Check whether note content carries this pin's ownership marker.
 * Reads the raw frontmatter block directly (deterministic — no dependency
 * on metadata cache freshness at decision time).
 */
function isOwnedPartyNoteContent(content: string, pinId: string): boolean {
  const frontmatter = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!frontmatter) return false;
  const markerLine = new RegExp(`^${PARTY_NOTE_MARKER_KEY}:\\s*(.+)$`, 'm').exec(frontmatter[1]);
  return markerLine != null && markerLine[1].trim() === pinId;
}

/** Ensure the folder chain for a note path exists */
async function ensureParentFolder(app: App, notePath: string): Promise<void> {
  const lastSlash = notePath.lastIndexOf('/');
  if (lastSlash === -1) return;
  const folder = notePath.slice(0, lastSlash);
  if (app.vault.getAbstractFileByPath(folder) != null) return;
  await app.vault.createFolder(folder).catch(() => {
    // Folder may have been created concurrently; the create call below
    // surfaces any real failure
  });
}

/**
 * Find a note carrying this pin's marker anywhere in the vault (via the
 * metadata cache). Used when the stored path is gone, so a renamed or moved
 * note is followed instead of duplicated.
 */
function findPartyNoteByMarker(app: App, pinId: string): ObsidianTFile | null {
  for (const file of app.vault.getMarkdownFiles()) {
    const marker: unknown = app.metadataCache.getFileCache(file)?.frontmatter?.[PARTY_NOTE_MARKER_KEY];
    if ((typeof marker === 'string' || typeof marker === 'number') && String(marker).trim() === pinId) return file;
  }
  return null;
}

/** Update an existing owned note's region atomically; 'blocked' if not owned */
async function updateOwnedPartyNote(app: App, file: ObsidianTFile, pinId: string, content: string): Promise<PartyNoteWriteResult> {
  // Pre-check outside process(): identical content must not touch the file
  const before = await app.vault.read(file);
  if (!isOwnedPartyNoteContent(before, pinId)) return 'blocked';
  if (mergePartyNoteContent(before, content) === before) return 'unchanged';

  let outcome: PartyNoteWriteResult = 'unchanged';
  await app.vault.process(file, (current) => {
    if (!isOwnedPartyNoteContent(current, pinId)) {
      outcome = 'blocked';
      return current;
    }
    const next = mergePartyNoteContent(current, content);
    if (next !== current) outcome = 'updated';
    return next;
  });
  return outcome;
}

/**
 * Create or update the pin's note with the given content.
 * - Missing file: a note with this pin's marker elsewhere (renamed or moved)
 *   is updated instead; otherwise the note is (re)created
 * - Existing file without this pin's marker: left untouched ('blocked')
 * - Identical content: no write ('unchanged')
 * - Lost create race (another pane created it first): falls back to update
 */
async function upsertPartyNote(app: App, pin: PartyPin, content: string): Promise<PartyNoteWriteResult> {
  const path = pin.partyNote?.path;
  if (path == null || path === '') return 'blocked';

  let existing = app.vault.getAbstractFileByPath(path);
  if (existing == null) {
    const moved = findPartyNoteByMarker(app, pin.id);
    if (moved != null) return updateOwnedPartyNote(app, moved, pin.id, content);
    await ensureParentFolder(app, path);
    try {
      await app.vault.create(path, content);
      return 'created';
    } catch (error) {
      existing = app.vault.getAbstractFileByPath(path);
      if (existing == null) throw error;
    }
  }
  if (!(existing instanceof ObsidianTFile)) return 'blocked';
  return updateOwnedPartyNote(app, existing, pin.id, content);
}

/** Listener for beacon-note renames (oldPath, newPath) */
type PartyNoteRenameListener = (oldPath: string, newPath: string) => void;
const renameListeners = new Set<PartyNoteRenameListener>();

/** Subscribe to vault renames; returns the unsubscribe function */
function onPartyNoteRenamed(listener: PartyNoteRenameListener): () => void {
  renameListeners.add(listener);
  return () => { renameListeners.delete(listener); };
}

/** Broadcast a vault rename to mounted beacons (called from main.ts) */
function notifyPartyNoteRenamed(oldPath: string, newPath: string): void {
  for (const listener of renameListeners) listener(oldPath, newPath);
}

/**
 * Trash the pin's note after verifying this pin generated it.
 * Uses fileManager.trashFile so the user's trash preference is honored.
 */
async function deletePartyNote(app: App, pin: PartyPin): Promise<PartyNoteDeleteResult> {
  const path = pin.partyNote?.path;
  if (path == null || path === '') return 'not-found';

  const existing = app.vault.getAbstractFileByPath(path);
  if (existing == null || !(existing instanceof ObsidianTFile)) return 'not-found';

  const content = await app.vault.read(existing);
  if (!isOwnedPartyNoteContent(content, pin.id)) return 'not-owned';

  await app.fileManager.trashFile(existing);
  return 'deleted';
}

